          <p class="ve-label ve-kicker">Galaha Estate</p>
          <h2 class="ve-h2" id="storyTitle" data-split>A bungalow built in <em>tea&rsquo;s golden age.</em></h2>
          <p class="ab-story__p ab-story__p--first" data-img="0">There is a building near the town of Galaha, in the central highlands of Sri Lanka, that has stood since the 1890s. It was built as a planter&rsquo;s residence: not a grand colonial manor, but a well-made working home for the man who ran the estate. Wide verandahs to catch the upland air. A long dining table for household and guests. Rooms that let in the morning light.</p>
          <p class="ab-story__p" data-img="1">The estate is part of the Galaha region, and the Galaha region is where Ceylon tea began. In 1867, just up the road at Loolecondera Estate, a 32-year-old Scotsman named James Taylor planted the island&rsquo;s first 21 acres of commercial tea. By 1873 the first exports had reached London. By the time this bungalow was built two decades later, tea had replaced coffee entirely, and these hills had become the centre of a global trade.</p>
          <p class="ab-story__pull" data-img="1">The planters who lived here watched an industry they had helped build, <em>from this very verandah.</em></p>
          <p class="ab-story__p" data-img="2">The bungalow survived the move from private estate to state management. In 1976 Sri Lanka&rsquo;s land reform laws created the Janatha Estates Development Board, and Galaha Estate, like hundreds of others, was nationalised. The JEDB era lasted until the early 1990s, when the estates returned to private management. The bungalow stood through it all.</p>
          <p class="ab-story__p" data-img="3">What you find today is a house that has been carefully restored: not stripped and renovated, but attended to. The original teak floors. The proportions of a colonial residence. The stone fireplace in the Planter&rsquo;s Lounge, unchanged since the 1890s. The long rear verandah, from which the mist over the tea looks exactly as it did to the first superintendent who stood there.</p>
          <p class="ab-story__p" data-img="4">We opened the bungalow as a heritage stay because we believe the best way to preserve a house is to live in it: to fill it with guests, light the fire, pour the tea, and let it do what it was built to do. A house is not a museum. <em>It is a home opened to people.</em></p>
        </div>
