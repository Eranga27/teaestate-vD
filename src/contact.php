    // The letter goes to /api/enquiry as URL-encoded data (Vercel functions don't parse multipart)
    document.getElementById('enquiry-form').addEventListener('submit', async function (e) {
      e.preventDefault();
      var form = this, errors = form.querySelector('.ct-errors'), missing = [];
      form.querySelectorAll('[required]').forEach(function (f) {
        var bad = !f.value.trim() || (f.type === 'email' && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(f.value.trim()));
        (f.closest('.ct-field') || f).classList.toggle('is-invalid', bad);
        f.setAttribute('aria-invalid', bad ? 'true' : 'false');
        if (bad) missing.push(f);
      });
      if (missing.length) {
        errors.hidden = false;
        errors.textContent = 'Nearly there: please fill in the highlighted parts of your letter.';
        missing[0].focus();
        return;
      }
      errors.hidden = true;
      // Anything on the guest's "Your stay" list travels in the message
      var message = form.elements.message, original = message.value, stay = form.querySelector('.ct-stay');
      if (stay && !stay.hidden && stay.querySelector('.ct-stay__check').checked) {
        message.value = original + '\n\nAlso on my list: ' + stay.querySelector('.ct-stay__list').textContent + '.';
      }
      var btn = form.querySelector('.ct-send'), label = btn.querySelector('span'), text = label.textContent;
      btn.disabled = true; label.textContent = 'Sending…';
      try {
        var res = await fetch('/api/enquiry', { method: 'POST', body: new URLSearchParams(new FormData(this)) });
        var data = await res.json().catch(function () { return {}; });
        message.value = original;
        if (res.ok && data.ok) {
          form.hidden = true;
          var sent = document.getElementById('form-success');
          sent.hidden = false; sent.focus();
          window.dataLayer = window.dataLayer || [];
          window.dataLayer.push({ event: 'enquiry_submitted', enquiry_type: form.elements['enquiry-type'].value });
        } else {
          errors.hidden = false;
          errors.textContent = (data && data.message) || 'Your letter could not be sent just now. Please try again, or WhatsApp us on +94 (0)777 874 555.';
          btn.disabled = false; label.textContent = text;
        }
      } catch (err) {
        message.value = original;
        errors.hidden = false;
        errors.textContent = 'The connection dropped. Please try again, or WhatsApp us on +94 (0)777 874 555.';
        btn.disabled = false; label.textContent = text;
      }
    });
  </script>
